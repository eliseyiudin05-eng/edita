export type SavedAcademyAssessment={
  moduleIndex:number;
  score:number;
  quizScore:number;
  passed:true;
  updatedAt:string;
};

export const ACADEMY_ASSESSMENT_VERSION=2;
export const ASSESSMENT_STORAGE_OFFSET=100;

export function assessmentStorageIndex(levelIndex:number){return ASSESSMENT_STORAGE_OFFSET+levelIndex}
export function assessmentPublicIndex(storageIndex:number){return storageIndex-ASSESSMENT_STORAGE_OFFSET}
export function isCurrentAssessmentStorageIndex(value:number){return Number.isInteger(value)&&value>=ASSESSMENT_STORAGE_OFFSET&&value<=ASSESSMENT_STORAGE_OFFSET+3}

export function savedAcademyAssessments(onboarding:unknown):SavedAcademyAssessment[]{
  if(!onboarding||typeof onboarding!=="object"||Array.isArray(onboarding))return [];
  const source=onboarding as Record<string,unknown>;
  if(Number(source.academyAssessmentVersion)!==ACADEMY_ASSESSMENT_VERSION)return [];
  const raw=source.academyAssessments;
  if(!Array.isArray(raw))return [];
  return raw.flatMap(item=>{
    if(!item||typeof item!=="object"||Array.isArray(item))return [];
    const value=item as Record<string,unknown>;
    const moduleIndex=Number(value.moduleIndex);
    const score=Number(value.score);
    const quizScore=Number(value.quizScore);
    if(!Number.isInteger(moduleIndex)||moduleIndex<0||moduleIndex>3||!Number.isFinite(score)||!Number.isFinite(quizScore)||value.passed!==true)return [];
    return [{moduleIndex,score,quizScore,passed:true as const,updatedAt:String(value.updatedAt||"")}];
  });
}

