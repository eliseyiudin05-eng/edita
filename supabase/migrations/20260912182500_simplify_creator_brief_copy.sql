Цель: показать EDITA живо и понятно, простыми словами и без громких рекламных фраз.

Что должно быть в видео:
• Начни ролик за 1–2 секунды с личной мысли или проблемы новичка. Например: «Сначала я путался в словах про монтаж».
• Покажи 2–4 настоящих экрана EDITA: первый урок, объяснение слова, помощника или конкурс.
• Расскажи своими словами, что стало понятнее.
• Говори только о своём опыте. Обещания заработка, работы и быстрого успеха оставь за пределами ролика.
• Личные данные, электронную почту, пароли, данные карты и коды доступа оставь за пределами ролика.
• В конце можно сказать: «Я тестирую EDITA — платформу, где монтаж объясняют с нуля».

Стиль:
• живой ролик от первого лица;
• можно с лицом или без лица;
• обычная речь, без заученного рекламного текста;
• аккуратный монтаж с небольшим количеством эффектов.

До начала съёмки автор и EDITA отдельно согласуют оплату и сроки.
